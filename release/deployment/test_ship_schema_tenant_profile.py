"""Independent complete-source profile fixtures; no runtime/profile authority.

Expected payload and function bytes below are the precommitted symbolic-v1
templates, not copied from a measured graph or generated by the parser under
test. Relation fixtures derive full app/production catalogs from source.
"""
import copy
import dataclasses
import hashlib
import json
import re
import unittest

import catalog_semantics as wire
import schema_tenant_profile as profile
import test_ship_schema_relation as relation_fixture

BASE = "a" * 40
HEAD = "b" * 40
EMPTY = hashlib.sha256(b"").hexdigest()
ACL = "MIGRATION_OWNER>MIGRATION_OWNER:EXECUTE:false;MIGRATION_OWNER>RUNTIME:EXECUTE:false"
EXPR = "(organization_id = (NULLIF(current_setting('app.current_organization_id'::text, true), ''::text))::uuid)"


def encoded(value):
    text = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    for char, escape in (("<", "\\u003c"), (">", "\\u003e"), ("&", "\\u0026"),
                         ("\u2028", "\\u2028"), ("\u2029", "\\u2029")):
        text = text.replace(char, escape)
    return (text + "\n").encode()


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def descriptions(raw_tenant):
    rows = []
    pattern = r'(?m)^var tenantRLSAdditiveProfileV([0-9]+) = \[\]string\{([^}]*)\}'
    for match in re.finditer(pattern, raw_tenant.decode()):
        version = int(match[1])
        if version < 2:
            continue
        members = re.findall(r'"([a-z_][a-z0-9_]*)"', match[2])
        payload = {"format_version": 1, "postgres_major": 17, "profile_version": version,
            "members": [{"schema": "public", "table": name, "policies": [
                {"name": "rereply_migration_access", "command": "*", "permissive": True,
                 "roles": ["MIGRATION_OWNER"], "using_expression": "true", "check_expression": "true"},
                {"name": "rereply_tenant_isolation", "command": "*", "permissive": True,
                 "roles": ["RUNTIME"], "using_expression": EXPR, "check_expression": EXPR}]} for name in members]}
        token = "v" + str(version) + ":sym1:" + digest(b"rereply-tenant-additive-policy-symbolic-v1\0" + encoded(payload))
        source = "SELECT '" + token + "'::text"
        definition = ("CREATE OR REPLACE FUNCTION public.rereply_tenant_policy_additive_fingerprint_v"
            + str(version) + "()\n RETURNS text\n LANGUAGE sql\n IMMUTABLE\n"
            " SET search_path TO 'pg_catalog'\nAS $function$" + source + "$function$\n")
        rows.append({"payload": payload, "function_source": source,
                     "function_definition": definition, "function_config": '["search_path=pg_catalog"]'})
    return sorted(rows, key=lambda row: row["payload"]["profile_version"])


def function_row(description):
    version = description["payload"]["profile_version"]
    return {"kind": "functions", "identity": "rereply_tenant_policy_additive_fingerprint_v" + str(version) + "(" + EMPTY + ")",
        "attributes": {"source_sha256": digest(description["function_source"].encode()),
            "definition_sha256": digest(description["function_definition"].encode()),
            "config_sha256": digest(description["function_config"].encode()), "security_definer": "false",
            "owner": "MIGRATION_OWNER", "acl": ACL, "volatility": "i", "parallel": "u",
            "strict": "false", "leakproof": "false", "language_sha256": digest(b"sql")}}


def pin(raw, path):
    return {"path": path, "bytes": len(raw), "sha256": digest(raw)}


def endpoint(raw_catalog, raw_globals, raw_tenant, role):
    document = json.loads(raw_catalog)
    # Wire-zero catalog hashing and logical schema version remain distinct.
    return {"role": role, "catalog": {**pin(raw_catalog, profile.CATALOG_PATH),
        "catalog_version": document["version"], "catalog_sha256": digest(wire._catalog_bytes(document["objects"]))},
        "globals": pin(raw_globals, profile.GLOBALS_PATH), "tenant_source": pin(raw_tenant, profile.TENANT_PATH)}


def bind(raws, relation_declaration=None, declaration=None):
    bc, ac, bg, ag, bt, at = raws
    relation_raw = None
    if relation_declaration is not None:
        relation_raw = encoded(relation_fixture.bind_documents(relation_declaration, *raws))
    value = copy.deepcopy(declaration) if declaration is not None else {
        "format_version": 1, "postgres_major": 17, "purpose": "tenant-additive-source-shape",
        "profiles": descriptions(at)}
    value.update(before=endpoint(bc, bg, bt, "before"), after=endpoint(ac, ag, at, "after"),
        relation=None if relation_raw is None else pin(relation_raw, profile.relation.SOURCE_PATH))
    return (encoded(value), relation_raw, *raws)


def scenario(*, production=False, prior=None, version=2, table=None):
    table = table or "source_profile_v" + str(version) + "_items"
    if prior is None:
        data = relation_fixture.declared_catalogs(mode="direct-tenant", production=production, table=table)
    else:
        _, _, _, ac, _, ag, _, at = prior
        data = relation_fixture.add_relation(ac, ag, at, mode="direct-tenant", table=table, version=version)
    raws, declaration = list(data[:6]), data[6]
    after = json.loads(raws[1])
    existing = {row["identity"] for row in after["objects"] if row["kind"] == "functions"}
    for description in descriptions(raws[5]):
        row = function_row(description)
        if row["identity"] not in existing:
            after["objects"].append(row)
    after["objects"].sort(key=lambda row: (row["kind"], row["identity"]))
    raws[1] = encoded(after)
    return bind(tuple(raws), declaration)


def retained(value):
    _, _, _, ac, _, ag, _, at = value
    return bind((ac, ac, ag, ag, at, at))


def rebind(value, *, raw_changes=None, declaration_change=None):
    desc = json.loads(value[0])
    rel = None if value[1] is None else json.loads(value[1])
    raws = list(value[2:])
    for index, raw in (raw_changes or {}).items():
        raws[index] = raw
    result = bind(tuple(raws), rel, desc)
    if declaration_change:
        desc = json.loads(result[0]); declaration_change(desc)
        result = (encoded(desc), *result[1:])
    return result


def mutate_catalog(value, mutate, *, before=False):
    index = 0 if before else 1
    document = json.loads(value[index + 2]); mutate(document)
    return rebind(value, raw_changes={index: encoded(document)})


class TenantProfileTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.value = scenario()

    def run_profile(self, value=None, **kw):
        return profile.classify_source(*(value or self.value), base_sha=kw.get("base", BASE), head_sha=kw.get("head", HEAD))

    def refused(self, value):
        with self.assertRaisesRegex(profile.TenantProfileSourceRefusal, "^tenant-profile-source-invalid$"):
            self.run_profile(value)

    def test_complete_app_introduction_and_fixed_precommitted_payload(self):
        result = self.run_profile()
        self.assertEqual(result.introduced_version, 2)
        self.assertEqual(result.retained_versions, ())
        self.assertEqual(result.profiles[0].payload_sha256, "01e1607b20e03c4520bbff8abb2898ad95cacd02a7d0b5a1070837eb6f7177b6")
        self.assertEqual(result.profiles[0].policy_digest, "46da66dd302f3ad5595bf5189fbd3b193e3af33c1b1bd7a99bbeb228b527ba98")
        self.assertEqual(len(result.explained), 1)
        self.assertEqual(len(result.residual), 7)

    def test_independent_production_catalog_and_no_runtime_claim(self):
        value = scenario(production=True)
        self.assertEqual(self.run_profile(value).introduced_version, 2)
        self.assertEqual(digest(wire._catalog_bytes(json.loads(value[2])["objects"])),
            "1c85a9ad0b9bb652ea21b51faa2ee887592dacb00c7f4b388de5ef5d6085a4e7")

    def test_append_exact_next_version_retains_previous(self):
        result = self.run_profile(scenario(prior=self.value, version=3))
        self.assertEqual((result.introduced_version, result.retained_versions), (3, (2,)))
        self.assertEqual(tuple(row.version for row in result.profiles), (2, 3))

    def test_retained_noop_has_no_explanations_or_source_exemption(self):
        result = self.run_profile(retained(self.value))
        self.assertEqual((result.introduced_version, result.retained_versions), (None, (2,)))
        self.assertEqual((result.explained, result.residual, result.tenant_changes), ((), (), ()))

    def test_retained_new_column_stays_residual(self):
        value = retained(self.value)
        def change(d):
            source = next(row for row in d["objects"] if row["kind"] == "columns" and row["identity"] == "source_profile_v2_items.value")
            row = copy.deepcopy(source); row["identity"] = "source_profile_v2_items.later"; row["attributes"]["position"] = "3"
            d["objects"].append(row); d["objects"].sort(key=lambda row: (row["kind"], row["identity"]))
        result = self.run_profile(mutate_catalog(value, change))
        self.assertEqual(result.explained, ())
        self.assertEqual([ref.identity for ref in result.residual], ["source_profile_v2_items.later"])

    def test_exact_external_source_identity(self):
        for base, head in ((BASE, BASE), ("A" * 40, HEAD), (True, HEAD), (BASE, "x")):
            with self.subTest(base=base, head=head):
                with self.assertRaises(profile.TenantProfileSourceRefusal): self.run_profile(base=base, head=head)

    def test_raw_catalog_and_all_endpoint_pins(self):
        for endpoint_name in ("before", "after"):
            for section in ("catalog", "globals", "tenant_source"):
                for key, bad in (("path", "elsewhere"), ("bytes", True), ("sha256", "0" * 64)):
                    with self.subTest(endpoint=endpoint_name, section=section, key=key):
                        self.refused(rebind(self.value, declaration_change=lambda d: d[endpoint_name][section].update({key: bad})))

    def test_logical_and_wire_versions_are_not_interchangeable(self):
        for key, bad in (("catalog_version", 17), ("catalog_version", True), ("catalog_sha256", "0" * 64)):
            self.refused(rebind(self.value, declaration_change=lambda d: d["after"]["catalog"].update({key: bad})))

    def test_profile_outer_schema_and_numeric_types(self):
        for key, bad in (("format_version", True), ("postgres_major", True), ("purpose", "approved"), ("extra", 1)):
            self.refused(rebind(self.value, declaration_change=lambda d: d.update({key: bad})))

    def test_profile_body_bool_hash_and_role_spoofs(self):
        changes = [lambda p: p.update(profile_version=True), lambda p: p.update(format_version=True),
            lambda p: p["members"][0]["policies"][0].update(permissive=1),
            lambda p: p["members"][0]["policies"][1].update(roles=["PUBLIC"]),
            lambda p: p["members"][0].update(table="organizations")]
        for mutate in changes:
            self.refused(rebind(self.value, declaration_change=lambda d: mutate(d["profiles"][0]["payload"])))

    def test_function_raw_preimages_must_match_independent_template(self):
        for key in ("function_source", "function_definition", "function_config"):
            self.refused(rebind(self.value, declaration_change=lambda d: d["profiles"][0].update({key: "untrusted"})))

    def test_function_catalog_attributes_are_complete(self):
        for key, bad in (("acl", "MIGRATION_OWNER>MIGRATION_OWNER:EXECUTE:false;MIGRATION_OWNER>PUBLIC:EXECUTE:false"),
                         ("owner", "OTHER"), ("security_definer", "true"), ("volatility", "v"),
                         ("source_sha256", "0" * 64), ("definition_sha256", "0" * 64),
                         ("config_sha256", "0" * 64), ("strict", "true"), ("leakproof", "true")):
            def change(d):
                next(row for row in d["objects"] if row["identity"].startswith("rereply_tenant_policy_additive_fingerprint_v2("))["attributes"][key] = bad
            self.refused(mutate_catalog(self.value, change))

    def test_retained_policy_or_acl_changes_refuse(self):
        value = retained(self.value)
        for identity, key, bad in (("source_profile_v2_items.rereply_tenant_isolation", "roles", "PUBLIC"),
                ("source_profile_v2_items.rereply_migration_access", "using_sha256", "0" * 64),
                ("source_profile_v2_items", "force_rls", "false")):
            def change(d):
                next(row for row in d["objects"] if row["identity"] == identity and row["kind"] in {"relations", "policies"})["attributes"][key] = bad
            self.refused(mutate_catalog(value, change))

    def test_core_function_edit_never_explained(self):
        def change(d):
            next(row for row in d["objects"] if row["identity"].startswith("rereply_tenant_policy_fingerprint("))["attributes"]["source_sha256"] = "0" * 64
        self.refused(mutate_catalog(self.value, change))

    def test_missing_relation_or_mixed_relation_binding(self):
        missing = rebind(self.value, declaration_change=lambda d: d.update(relation=None))
        self.refused((missing[0], None, *missing[2:]))
        other = scenario(table="another_profile_table")
        self.refused((self.value[0], other[1], *self.value[2:]))

    def test_mutating_input_containers_cannot_change_returned_data(self):
        value = list(self.value); result = self.run_profile(value)
        value[0] = b"bad"
        self.assertEqual(result, self.run_profile())
        with self.assertRaises(dataclasses.FrozenInstanceError): result.profiles[0].version = 3
        with self.assertRaises(TypeError): profile.classify_source(result, *self.value[1:], base_sha=BASE, head_sha=HEAD, verdict=True)

    def test_noncanonical_duplicate_and_malformed_documents(self):
        for raw in (b"{}\n", self.value[0][:-1], b'{"format_version":1,"format_version":1}\n', b'[]\n', b'\xff'):
            self.refused((raw, *self.value[1:]))

    def test_complete_oversized_documents_are_counted_before_decode(self):
        large = encoded({"padding": "x" * profile.MAX_DOCUMENT})
        self.assertGreater(len(large), profile.MAX_DOCUMENT)
        self.refused((self.value[0], self.value[1], large, *self.value[3:]))
        declaration = encoded({"padding": "x" * profile.MAX_DECLARATION})
        self.refused((declaration, *self.value[1:]))

    def test_total_raw_role_budget_counts_aliases(self):
        doc = encoded({"padding": "x" * ((4 << 20) - 100)})
        tiny = b"{}\n"
        with self.assertRaises(profile.TenantProfileSourceRefusal):
            profile._budget(tiny, None, (doc, doc, b" " * 201, b" " * 201, tiny, tiny))

    def test_preserved_pair_checks_all_profiles_without_fresh_clock(self):
        value = retained(self.value)
        self.assertIsNone(profile.validate_retained_pair(*value[2:]))
        def change(d):
            next(row for row in d["objects"] if row["identity"].startswith("rereply_tenant_policy_additive_fingerprint_v2("))["attributes"]["source_sha256"] = "0" * 64
        changed = mutate_catalog(value, change)
        with self.assertRaises(profile.TenantProfileSourceRefusal): profile.validate_retained_pair(*changed[2:])

    def test_version_gap_and_deletion(self):
        value = retained(self.value)
        raw = value[-1].replace(b"tenantRLSAdditiveProfileV2", b"tenantRLSAdditiveProfileV4")
        self.refused(rebind(value, raw_changes={5: raw}))
        raw = re.sub(rb'(?m)^var tenantRLSAdditiveProfileV2 = \[\]string\{[^}]*\}\n?', b'', value[-1])
        self.refused(rebind(value, raw_changes={5: raw}))

    def test_constant_core_and_v1_declarations_remain_exact(self):
        for old, new in ((b"tenantRLSRoutingVersion         = 5", b"tenantRLSRoutingVersion         = 6"),
                         (b'"whatsapp_coexistence_states"', b'"organizations"')):
            raw = self.value[-1].replace(old, new)
            self.assertNotEqual(raw, self.value[-1])
            self.refused(rebind(self.value, raw_changes={5: raw}))

    def test_renamed_member_cannot_hide_existing_relation(self):
        raw = self.value[-1].replace(b'"source_profile_v2_items"', b'"organizations"')
        self.refused(rebind(self.value, raw_changes={5: raw}))

    def test_retained_declaration_cannot_disappear_behind_noop(self):
        value = retained(self.value)
        self.refused((b"null\n", *value[1:]))

    def test_unknown_function_version_not_exempted_by_valid_v2(self):
        def change(d):
            row = copy.deepcopy(next(row for row in d["objects"] if row["identity"].startswith("rereply_tenant_policy_additive_fingerprint_v2(")))
            row["identity"] = row["identity"].replace("_v2(", "_v9(")
            d["objects"].append(row); d["objects"].sort(key=lambda row: (row["kind"], row["identity"]))
        self.refused(mutate_catalog(self.value, change))

    def test_unrelated_catalog_edit_remains_full_residual(self):
        def change(d):
            next(row for row in d["objects"] if row["kind"] == "relations" and row["identity"] == "organizations")["attributes"]["owner"] = "OTHER"
        result = self.run_profile(mutate_catalog(self.value, change))
        self.assertIn("organizations", [ref.identity for ref in result.residual])


